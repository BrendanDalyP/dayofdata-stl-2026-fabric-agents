import { existsSync, readdirSync, readFileSync } from "node:fs";
import { resolve } from "node:path";

import { describe, expect, it } from "vitest";

import { connectorConfigs, connectorRuntimes } from "@/lib/connectors";

// This app owns its connector wiring: the CLI's `@generated` marker is removed, so
// `npx rayfin connector add/remove` print the wiring instead of rewriting the file
// (decorated entity classes can't be bundled for the browser, so configs use field-name arrays).

const appRoot = process.cwd();
// The CLI writes LF; normalizing keeps a CRLF checkout from failing these tests.
const current = readFileSync(resolve(appRoot, "src/lib/connectors.ts"), "utf8").replace(/\r\n/g, "\n");

/** The scaffolded connector names. */
function scaffoldedConnectors(): string[] {
    const directory = resolve(appRoot, "rayfin/connectors");
    return existsSync(directory)
        ? readdirSync(directory, { withFileTypes: true })
            .filter((entry) => entry.isDirectory() && existsSync(resolve(directory, entry.name, "schema.ts")))
            .map((entry) => entry.name)
            .sort()
        : [];
}

describe("src/lib/connectors.ts", () => {
    it("keeps the app-owned block first and no @generated marker, so the CLI leaves it alone", () => {
        const end = current.indexOf("// #endregion rayfin:app-owned");
        expect(current.indexOf("// #region rayfin:app-owned")).toBe(0);
        expect(end).toBeGreaterThan(0);
        expect(current.slice(0, end)).toContain("export type SemanticModelConnectors");
        expect(current).not.toMatch(/^\/\/ @generated by `rayfin connector add`/m);
    });

    it("wires every scaffolded connector", () => {
        expect(Object.keys(connectorConfigs).sort()).toEqual(scaffoldedConnectors());
    });

    it("keeps connector runtimes empty (the lakehouse connector runs server-side)", () => {
        expect(connectorRuntimes).toEqual({});
    });
});
