"""Runs verify_answers.sql and writes the expected answers to:
  ground_truth.csv                                  (one file per agent: ground_truth_<agent>.csv, for evaluate_agent.ipynb)
  ../03-fabric-app/src/agent/recorded.ts            (offline-mode answers for the app)
  expected-answers.md                               (for backup slides and rehearsal)

Usage (after `az login`): python make_ground_truth.py   (env SQL_SERVER, SQL_DB)
"""
import csv, os, pathlib, re
import mssql_python

HERE = pathlib.Path(__file__).parent
AGENT = {"S": "sales", "O": "operations", "P": "planning"}
EUR = re.compile(r"eur$")

sql = (HERE / "verify_answers.sql").read_text(encoding="utf-8")
blocks = [b.strip() for b in re.split(r"^\s*GO\s*$", sql, flags=re.M) if b.strip()]

conn = mssql_python.connect(
    f"Server={os.environ['SQL_SERVER']},1433;Database={os.environ['SQL_DB']};Encrypt=yes;Authentication=ActiveDirectoryDefault;"
)
cur = conn.cursor()


def fmt(col, v):
    if v is None:
        return "–"
    if hasattr(v, "isoformat"):
        return v.strftime("%b %Y") if col == "month" else v.isoformat()
    if isinstance(v, (int, float)) or type(v).__name__ == "Decimal":
        if col.endswith("pct"):
            return f"{float(v):.1f}%"
        if EUR.search(col):
            return f"€{float(v):,.0f}"
        return f"{float(v):,.0f}"
    return str(v)


def pretty(col):
    return col.replace("_eur", " (EUR)").replace("_pct", " (%)").replace("_", " ").capitalize()


rows_out, recorded, md = {k: [] for k in AGENT.values()}, [], ["# Expected answers (from verify_answers.sql)\n"]
for b in blocks:
    m = re.search(r"--\s*([SOP]\d)\s*·\s*\w+\s*·\s*(.+)", b)
    if not m:
        continue
    qid, question = m.group(1), m.group(2).strip()
    agent = AGENT[qid[0]]
    cur.execute(b)
    cols = [c[0] for c in cur.description]
    data = cur.fetchall()
    table = ["| " + " | ".join(pretty(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    table += ["| " + " | ".join(fmt(c, v) for c, v in zip(cols, r)) + " |" for r in data]
    table_md = "\n".join(table)
    period = "2022 to 21 Aug" if "2022-08-01" not in b else "Jan–Jul 2022"
    answer = f"Here is the answer for **{period}**, in euros.\n\n{table_md}"
    rows_out[agent].append({"question": question, "expected_answer": table_md.replace("\n", " ")})
    recorded.append({"agent": agent, "question": question, "answer": answer})
    md.append(f"## {qid} · {agent} · {question}\n\n{table_md}\n")
    print(f"{qid} {agent:<10} {len(data)} rows  {question}")
conn.close()

for agent, rows in rows_out.items():
    with open(HERE / f"ground_truth_{agent}.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["question", "expected_answer"])
        w.writeheader()
        w.writerows(rows)

(HERE / "expected-answers.md").write_text("\n".join(md), encoding="utf-8")

import json
ts = "// Generated by labs/01-data-agent/make_ground_truth.py from verify_answers.sql. Do not edit.\n"
ts += 'import type { AgentKey } from "./team";\n\n'
ts += "export const RECORDED: Array<{ agent: AgentKey; question: string; answer: string }> = "
ts += json.dumps(recorded, ensure_ascii=False, indent=2) + ";\n"
(HERE.parent / "03-fabric-app" / "src" / "agent" / "recorded.ts").write_text(ts, encoding="utf-8")
print("wrote ground_truth_*.csv, expected-answers.md, recorded.ts")
